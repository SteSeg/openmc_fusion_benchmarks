import os
import sandy
import openmc


def zaid_to_zam(zaid: int) -> tuple:
    """Converts a ZAID to Z, A, and M.

    Parameters
    ----------
    zaid : int
    nuclide ZAID

    Returns
    -------
    tuple
        Z, A, and M values
    """
    zaid_str = str(zaid)

    # Extract Z, A, and M based on ZAID length
    if len(zaid_str) == 4:  # Handles cases like H-1 (1001)
        Z = int(zaid_str[0])  # First digit for Z
        A = int(zaid_str[1:])  # Last 3 digits for A
        M = 0  # Assuming ground state if no additional digit
    elif len(zaid_str) == 5:  # Typical ZAID with 5 digits
        Z = int(zaid_str[:2])  # First 2 digits for Z
        A = int(zaid_str[2:])  # Last 3 digits for A
        M = 0  # Assuming ground state
    elif len(zaid_str) == 6:  # ZAID with 6 digits, includes isomeric state
        Z = int(zaid_str[:3])  # First 3 digits for Z
        A = int(zaid_str[3:5])  # Next 2 digits for A
        M = int(zaid_str[5])  # Last digit represents isomeric state

    return (Z, A, M)


def get_nuclide_zaid(nuclide):
    """Gets the ZAID of a nuclide from its name as a GNDS string (e.g. 'H1',
    'U238) or as a ZAM tuple (e.g. (1, 1, 0)).
    See openmc.data.zam() for more details.

    Parameters
    ----------
    nuclide : int or str or tuple
        The nuclide identifier or name

    Returns
    -------
    int
        The ZAID of the nuclide
    """
    if type(nuclide) == int:
        return nuclide
    elif type(nuclide) == str:
        return openmc.data.zam(nuclide)[0]*1000 + openmc.data.zam(nuclide)[1]
    elif type(nuclide) == tuple:
        return nuclide[0]*1000 + nuclide[1]


def get_nuclide_gnds(nuclide: Union[str, int]) -> str:
    """Gets the GNDS name from a nuclide ZAID

    Parameters
    ----------
    nuclide : str or int
        The nuclide ZAID or GNDS name

    Returns
    -------
    str
        The GNDS name of the nuclide
    """
    if type(nuclide) == str:
        return nuclide
    elif type(nuclide) == int:
        zam = zaid_to_zam(nuclide)
        return openmc.data.gnds_name(zam[0], zam[1], zam[2])


def get_reaction_mt(reaction: Union[str, int]) -> int:
    """Gets the MT value from a reaction name

    Parameters
    ----------
    reaction : str or int
        The reaction name or MT value

    Returns
    -------
    int
        The MT value of the reaction
    """
    try:
        mt = openmc.data.REACTION_MT[reaction]
    except KeyError:
        mt = reaction

    return mt


def remove_ace_files(directory: str, lib_name: str):
    """Remove ACE files generated by sandy from a given directory.

    Parameters
    ----------
    directory : str
        Path to the directory where the ACE files are located
    lib_name : str
        Name of the nuclear data library used to generate the ACE files
    """
    # List of extensions to remove
    extensions = ['03c', '03c.xsd', lib_name]

    # Loop through each extension and remove matching files
    directory_path = Path(directory)

    for ext in extensions:
        for file_path in directory_path.glob(f'*.{ext}'):
            try:
                file_path.unlink()  # equivalent to os.remove
                print(f"Removed {file_path}")
            except Exception as e:
                print(f"Error removing {file_path}: {e}")


def get_ace_files(nsamples: int, lib_name: str, nuclide: Union[str, int],
                  reaction: Union[str, int], nprocesses: int, error: float):
    """Generate ACE files for a given nuclide and reaction from a defined 
    nuclear data library using sandy.

    Parameters
    ----------
    nsamples : int
        Number of perturbed cross section samples to generate
    lib_name : str
        Name of the nuclear data library to generate the ACE files from
    nuclide : str or int
        Identifier of the nuclide for which the cross section is perturbed
        (GNDS, ZAID)
    reaction : str or int
        String name or MT value for the specific reaction to perturb
    nprocesses : int
        Number of processes for parallel processing
    error : float
        Error tolerance for processing in sandy

    Returns
    -------
    list
        List of ACE files generated
    """
    # convert nuclide to ZAID
    nuclide_zaid = get_nuclide_zaid(nuclide)
    reaction_mt = get_reaction_mt(reaction)
    tape = sandy.get_endf6_file(lib_name, "xs", nuclide_zaid*10, to_file=True)

    # Generate perturbations
    perturbations = tape.get_perturbations(
        nsamples,
        njoy_kws=dict(
            err=error,
            chi=False,
            mubar=False,
            xs=True,
            nubar=False,
            verbose=True,
            errorr33_kws=dict(mt=reaction_mt)
        ),
    )

    # Apply perturbations and generate ACE files
    ace_files = tape.apply_perturbations(
        perturbations,
        processes=nprocesses,
        njoy_kws=dict(err=error),
        to_ace=True,
        to_file=True,
        ace_kws=dict(
            err=error,
            temperature=294,
            verbose=True,
            purr=True,
            heatr=True,
            thermr=True,
            gaspr=True,
            groupr=True,
            errorr=True,
            heatr_kws={'local': True}
        ),
        verbose=True,
    )

    # Optionally return or process 'outs' if needed
    return ace_files


def ace_to_hdf5(nsamples: int, lib_name: str, nuclide: Union[str, int],
                remove_ace: bool = True):
    """Convert ACE files to HDF5 using OpenMC.

    Parameters
    ----------
    nsamples : int
        Number of perturbed cross section samples to convert
    lib_name : str
        Name of the nuclear data library used to generate the ACE files
    nuclide : str or int
        Identifier of the nuclide for which the cross section is perturbed
        (GNDS, ZAID)
    remove_ace : bool, optional
        removes the original ACE files, by default True
    """
    # convert nuclide to gnds and ZAID
    nuclide_gnds = get_nuclide_gnds(nuclide)
    nuclide_zaid = get_nuclide_zaid(nuclide)

    directory = f"{nuclide_gnds}_{lib_name}"
    directory_path = Path(directory)
    directory_path.mkdir(parents=True, exist_ok=True)

    for n in range(0, nsamples):
        acefile = f"{nuclide_zaid}_{n}.03c"
        h5file = f"{directory}/{nuclide_gnds}_{n}_{lib_name}.h5"

        # Convert ACE to HDF5 using OpenMC
        try:
            nuc_data = openmc.data.IncidentNeutron.from_ace(acefile)
            print(f'Writing to {Path.cwd() / h5file}')
            nuc_data.export_to_hdf5(h5file)
        except FileNotFoundError:
            print(f'Error: ACE file {acefile} not found.')
        except Exception as e:
            print(f'Error processing {acefile}: {e}')

    if remove_ace:
        remove_ace_files('', lib_name)


def perturb_to_hdf5(nsamples: int, lib_name: str, nuclide: Union[str, int],
                    reaction: Union[str, int], nprocesses: int = 1,
                    error: float = .001):
    """Perturb nuclear data and convert to HDF5 format.

    Parameters
    ----------
    nsamples : int
        Number of perturbed cross section samples to generate
    lib_name : str
        Name of the nuclear data library to generate the ACE files from
    nuclide : int or str
        Identifier of the nuclide for which the cross section is perturbed
        (GNDS, ZAID)
    reaction : str or int
        Str name or MT value for the specific reaction to perturb
    nprocesses : int, optional
        Number of processes for parallel processing, by default 1
    error : float, optional
        Error tolerance for processing in sandy, by default .001
    """
    get_ace_files(nsamples, lib_name, nuclide, reaction, nprocesses, error)
    ace_to_hdf5(nsamples,  lib_name, nuclide, remove_ace=True)


def get_env_variable(var_name: str) -> str:
    """Get the value of an environment variable.

    Parameters
    ----------
    var_name : str
        The name of the environment variable.

    Returns
    -------
    str
        The value of the environment variable.
    """
    value = os.getenv(var_name)
    if value is None:
        return f"Environment variable '{var_name}' is not set."
    return value


def rewrite_xs_xml(new_xs_file: str = 'cross_sections_mod.xml'):
    """Rewrite the cross_sections.xml file locally, in order not to modify the
    original file.

    Parameters
    ----------
    new_xs_file : str, optional
        Name of the new xs file to be created,
        by default 'cross_sections_mod.xml'
    """
    # read xs file
    model_xs_file = get_env_variable('OPENMC_CROSS_SECTIONS')
    myxs = openmc.data.DataLibrary.from_xml(model_xs_file)
    myxs.export_to_xml(new_xs_file)


def create_xs_dict(xs_h5_file: str, nuclide: str, type: str = 'neutron') -> dict:
    """Create a dictionary with the correct format for an cross_sections.xml file
    for a given target nuclide and the path to its corresponding h5 xs file.


    Parameters
    ----------
    xs_h5_file : str
        Path to the target nuclide h5 xs file
    nuclide : str
        Nuclide name in gnds format
    type : str, optional
        Type of incident particle (i.e. neutron, photon), by default 'neutron'

    Returns
    -------
    dict
        Dictionary with the path to the h5 xs file, the type of incident
        particle and the target nuclide
    """
    return {'path': xs_h5_file, 'type': type, 'materials': [nuclide]}


def perturb_xs_xml(xs_file: str, xs_h5_file: str, nuclide: str):
    """Perturb the cross_sections.xml file by replacing the original path of a
    nuclide xs with a new path to a new (perturbed) h5 xs file.

    Parameters
    ----------
    xs_file : str
        Name of the xs xml file to perturb
    xs_h5_file : str
        Path to the new (perturbed) h5 xs file
    nuclide : str
        Nuclide name in gnds format
    """
    # read xs file
    myxs = openmc.data.DataLibrary.from_xml(xs_file)
    try:
        myxs.libraries.get_by_material(nuclide)['path'] = xs_h5_file
    except TypeError:
        myxs.append(create_xs_dict(xs_h5_file, nuclide))
    # export to modified cross_sections xml file
    myxs.export_to_xml(xs_file)
